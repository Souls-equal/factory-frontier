import { fractalNoise2D, smoothstep } from '../noise';

/**
 * Deterministic terrain heightfield — the authoritative gameplay surface.
 *
 * Design (documented in `docs/TECHNICAL_ARCHITECTURE.md`, Appendix C):
 * - The world is a finite square grid of heights sampled from seeded fractal
 *   noise. Nothing here imports Three.js: the terrain is plain data that the
 *   renderer *reads* (`getRenderData()`), never the other way round.
 * - Height queries interpolate over exactly the same triangle split the mesh
 *   uses, so the rendered surface and the collision surface cannot drift apart.
 * - Normals/slopes are derived analytically from those triangles, which gives
 *   physics a stable slope signal without touching mesh geometry.
 * - The layout is a small, deliberate exploration area: a flat outpost clearing,
 *   rolling hills and a raised boundary ridge that closes the horizon.
 *
 * Chunk-based streaming (Phase 10) can reuse this class per chunk: everything is
 * expressed in grid coordinates with an explicit origin offset.
 */

export interface TerrainNormal {
  readonly x: number;
  readonly y: number;
  readonly z: number;
}

export interface TerrainBounds {
  readonly minX: number;
  readonly maxX: number;
  readonly minZ: number;
  readonly maxZ: number;
}

export interface TerrainOptions {
  readonly seed: number;
  readonly sizeMeters: number;
  /** Cells per side. Vertices per side = resolution + 1. */
  readonly resolution: number;
  readonly heightScale: number;
  readonly spawnFlatRadius: number;
  readonly rimHeight: number;
  /** World-space origin of the grid centre (used by future chunks). */
  readonly originX?: number;
  readonly originZ?: number;
}

export interface TerrainRenderData {
  /** Flat XYZ positions, row-major over Z then X. */
  readonly positions: Float32Array;
  /** Smooth per-vertex normals matching `positions`. */
  readonly normals: Float32Array;
  /** Triangle indices (two triangles per cell). */
  readonly indices: Uint32Array;
  readonly vertexCount: number;
  readonly triangleCount: number;
}

/** Gameplay-facing terrain contract consumed by the player and, later, machines. */
export interface TerrainQuery {
  readonly bounds: TerrainBounds;
  readonly size: number;
  readonly resolution: number;
  readonly cellSize: number;
  /** True when paired wall collisions resolve vertical column edges. */
  readonly verticalWalls?: boolean;
  heightAt(x: number, z: number): number;
  /** Optional footprint-aware support below the current feet (for stepped terrain). */
  groundBelow?(x: number, z: number, feetY: number, radius: number): number;
  normalAt(x: number, z: number): TerrainNormal;
  /** Slope angle in radians (0 = flat). */
  slopeAt(x: number, z: number): number;
  contains(x: number, z: number): boolean;
  clampXZ(x: number, z: number): { readonly x: number; readonly z: number };
}

const FBM_OPTIONS = Object.freeze({
  octaves: 4,
  frequency: 1 / 78,
  persistence: 0.5,
  lacunarity: 2.03,
});

/**
 * Maximum steepness (rise/run) generated anywhere on the surface.
 *
 * The relaxation pass below enforces it, which keeps the whole finite area
 * traversable and prevents the player from being funnelled into unwalkable
 * walls. Steeper-than-walkable terrain is still handled by the player physics
 * (see `maxWalkableSlope`); it simply is not generated by the default world.
 */
export const GENERATED_MAX_SLOPE_TANGENT = 0.72;

const SLOPE_LIMIT_PASSES = 200;

const DETAIL_OPTIONS = Object.freeze({
  octaves: 3,
  frequency: 1 / 24,
  persistence: 0.45,
  lacunarity: 2.11,
});

export class TerrainHeightfield implements TerrainQuery {
  readonly size: number;
  readonly resolution: number;
  readonly cellSize: number;
  readonly bounds: TerrainBounds;

  private readonly seed: number;
  private readonly heightScale: number;
  private readonly spawnFlatRadius: number;
  private readonly rimHeight: number;
  private readonly originX: number;
  private readonly originZ: number;
  private readonly heights: Float32Array;
  private readonly verticesPerSide: number;

  constructor(options: TerrainOptions) {
    if (!Number.isFinite(options.sizeMeters) || options.sizeMeters <= 0) {
      throw new RangeError(`sizeMeters must be positive (received ${options.sizeMeters}).`);
    }
    if (!Number.isInteger(options.resolution) || options.resolution < 2) {
      throw new RangeError(`resolution must be an integer >= 2 (received ${options.resolution}).`);
    }

    this.seed = options.seed | 0;
    this.size = options.sizeMeters;
    this.resolution = options.resolution;
    this.cellSize = options.sizeMeters / options.resolution;
    this.heightScale = options.heightScale;
    this.spawnFlatRadius = options.spawnFlatRadius;
    this.rimHeight = options.rimHeight;
    this.originX = options.originX ?? 0;
    this.originZ = options.originZ ?? 0;
    this.verticesPerSide = options.resolution + 1;

    const half = this.size / 2;
    this.bounds = Object.freeze({
      minX: this.originX - half,
      maxX: this.originX + half,
      minZ: this.originZ - half,
      maxZ: this.originZ + half,
    });

    this.heights = this.generateHeights();
  }

  contains(x: number, z: number): boolean {
    if (!Number.isFinite(x) || !Number.isFinite(z)) {
      return false;
    }
    return (
      x >= this.bounds.minX && x <= this.bounds.maxX && z >= this.bounds.minZ && z <= this.bounds.maxZ
    );
  }

  clampXZ(x: number, z: number): { readonly x: number; readonly z: number } {
    if (!Number.isFinite(x) || !Number.isFinite(z)) {
      throw new RangeError('Terrain coordinates must be finite numbers.');
    }
    return {
      x: Math.min(Math.max(x, this.bounds.minX), this.bounds.maxX),
      z: Math.min(Math.max(z, this.bounds.minZ), this.bounds.maxZ),
    };
  }

  /**
   * Height at a world position.
   *
   * Coordinates outside the finite area are clamped to the edge rather than
   * extrapolated, so a physics query can never read unrelated memory. Callers
   * that need to reject out-of-world positions use `contains()`.
   */
  heightAt(x: number, z: number): number {
    if (!Number.isFinite(x) || !Number.isFinite(z)) {
      throw new RangeError('Terrain queries require finite coordinates.');
    }

    const clamped = this.clampXZ(x, z);
    const gx = (clamped.x - this.bounds.minX) / this.cellSize;
    const gz = (clamped.z - this.bounds.minZ) / this.cellSize;

    const i = Math.min(Math.floor(gx), this.resolution - 1);
    const j = Math.min(Math.floor(gz), this.resolution - 1);
    const fx = gx - i;
    const fz = gz - j;

    const h00 = this.heightAtGrid(i, j);
    const h10 = this.heightAtGrid(i + 1, j);
    const h01 = this.heightAtGrid(i, j + 1);
    const h11 = this.heightAtGrid(i + 1, j + 1);

    // Same triangle split as `getRenderData()`: (a, c, b) and (b, c, d).
    if (fx + fz <= 1) {
      return h00 + (h10 - h00) * fx + (h01 - h00) * fz;
    }
    return h11 + (h01 - h11) * (1 - fx) + (h10 - h11) * (1 - fz);
  }

  normalAt(x: number, z: number): TerrainNormal {
    const clamped = this.clampXZ(x, z);
    const gx = (clamped.x - this.bounds.minX) / this.cellSize;
    const gz = (clamped.z - this.bounds.minZ) / this.cellSize;

    const i = Math.min(Math.floor(gx), this.resolution - 1);
    const j = Math.min(Math.floor(gz), this.resolution - 1);
    const fx = gx - i;
    const fz = gz - j;

    const h00 = this.heightAtGrid(i, j);
    const h10 = this.heightAtGrid(i + 1, j);
    const h01 = this.heightAtGrid(i, j + 1);
    const h11 = this.heightAtGrid(i + 1, j + 1);

    if (fx + fz <= 1) {
      return normalizeNormal((h00 - h10) * this.cellSize, this.cellSize * this.cellSize, (h00 - h01) * this.cellSize);
    }
    return normalizeNormal((h01 - h11) * this.cellSize, this.cellSize * this.cellSize, (h10 - h11) * this.cellSize);
  }

  slopeAt(x: number, z: number): number {
    const normal = this.normalAt(x, z);
    return Math.acos(Math.min(1, Math.max(-1, normal.y)));
  }

  /** Raw grid height (no interpolation). Exposed for deterministic testing. */
  heightAtGrid(i: number, j: number): number {
    if (!Number.isInteger(i) || !Number.isInteger(j)) {
      throw new RangeError('Grid indices must be integers.');
    }
    if (i < 0 || j < 0 || i >= this.verticesPerSide || j >= this.verticesPerSide) {
      throw new RangeError(`Grid index (${i}, ${j}) is outside the terrain.`);
    }
    // Bounds are validated above; the cast only satisfies the index signature.
    return this.heights[j * this.verticesPerSide + i] as number;
  }

  /** Highest point of the terrain (useful for lighting/culling decisions). */
  get maxHeight(): number {
    let max = -Infinity;
    for (const height of this.heights) {
      if (height > max) {
        max = height;
      }
    }
    return max;
  }

  /**
   * Geometry source for the renderer. The renderer must not modify the terrain;
   * it only turns this data into a mesh.
   */
  getRenderData(): TerrainRenderData {
    const side = this.verticesPerSide;
    const vertexCount = side * side;
    const positions = new Float32Array(vertexCount * 3);
    const normals = new Float32Array(vertexCount * 3);
    const indices = new Uint32Array(this.resolution * this.resolution * 6);

    for (let j = 0; j < side; j += 1) {
      for (let i = 0; i < side; i += 1) {
        const index = j * side + i;
        const height = this.heightAtGrid(i, j);
        positions[index * 3] = this.bounds.minX + i * this.cellSize;
        positions[index * 3 + 1] = height;
        positions[index * 3 + 2] = this.bounds.minZ + j * this.cellSize;

        // Central differences give smooth vertex normals that match the
        // analytic triangle normals used by physics closely enough for shading.
        const left = this.heightAtGrid(Math.max(i - 1, 0), j);
        const right = this.heightAtGrid(Math.min(i + 1, side - 1), j);
        const back = this.heightAtGrid(i, Math.max(j - 1, 0));
        const front = this.heightAtGrid(i, Math.min(j + 1, side - 1));
        const spanX = (Math.min(i + 1, side - 1) - Math.max(i - 1, 0)) * this.cellSize || this.cellSize;
        const spanZ = (Math.min(j + 1, side - 1) - Math.max(j - 1, 0)) * this.cellSize || this.cellSize;

        const normal = normalizeNormal(
          -(right - left) / spanX,
          1,
          -(front - back) / spanZ,
        );
        normals[index * 3] = normal.x;
        normals[index * 3 + 1] = normal.y;
        normals[index * 3 + 2] = normal.z;
      }
    }

    let cursor = 0;
    for (let j = 0; j < this.resolution; j += 1) {
      for (let i = 0; i < this.resolution; i += 1) {
        const a = j * side + i;
        const b = j * side + i + 1;
        const c = (j + 1) * side + i;
        const d = (j + 1) * side + i + 1;

        // Upper-left triangle (a, c, b) then lower-right triangle (b, c, d).
        // Winding is counter-clockwise when viewed from +Y.
        indices[cursor] = a;
        indices[cursor + 1] = c;
        indices[cursor + 2] = b;
        indices[cursor + 3] = b;
        indices[cursor + 4] = c;
        indices[cursor + 5] = d;
        cursor += 6;
      }
    }

    return {
      positions,
      normals,
      indices,
      vertexCount,
      triangleCount: this.resolution * this.resolution * 2,
    };
  }

  private generateHeights(): Float32Array {
    const side = this.verticesPerSide;
    const heights = new Float32Array(side * side);

    for (let j = 0; j < side; j += 1) {
      for (let i = 0; i < side; i += 1) {
        const x = this.bounds.minX + i * this.cellSize;
        const z = this.bounds.minZ + j * this.cellSize;
        heights[j * side + i] = this.sampleTerrainHeight(x, z);
      }
    }

    this.limitSlopes(heights);
    return heights;
  }

  /**
   * Relax the heightfield until no two neighbours differ by more than the
   * configured maximum slope allows.
   *
   * This is a deterministic smoothing pass (no randomness, fixed iteration
   * order), so the same seed still produces the same terrain. It is what makes
   * the "smooth transitions" requirement true by construction instead of by
   * luck with noise parameters.
   */
  private limitSlopes(heights: Float32Array): void {
    const side = this.verticesPerSide;
    const maxDelta = this.cellSize * GENERATED_MAX_SLOPE_TANGENT;

    for (let pass = 0; pass < SLOPE_LIMIT_PASSES; pass += 1) {
      let changed = false;

      for (let j = 0; j < side; j += 1) {
        for (let i = 0; i < side - 1; i += 1) {
          changed = relaxPair(heights, j * side + i, j * side + i + 1, maxDelta) || changed;
        }
      }
      for (let i = 0; i < side; i += 1) {
        for (let j = 0; j < side - 1; j += 1) {
          changed = relaxPair(heights, j * side + i, (j + 1) * side + i, maxDelta) || changed;
        }
      }

      if (!changed) {
        break;
      }
    }
  }

  /** Height field function before rasterization to the grid. */
  private sampleTerrainHeight(x: number, z: number): number {
    const base = fractalNoise2D(this.seed, x, z, FBM_OPTIONS);
    const detail = fractalNoise2D(this.seed ^ 0x5f3759df, x, z, DETAIL_OPTIONS);

    // Rolling hills: 0..1 noise remapped to ±1 around zero so the clearing has
    // both rises and dips instead of a uniform slope.
    let height = (base - 0.5) * this.heightScale * 2 + (detail - 0.5) * this.heightScale * 0.35;

    // Flatten the outpost clearing: full flattening in the middle, easing out.
    const distance = Math.hypot(x - this.originX, z - this.originZ);
    const flatten = 1 - smoothstep(this.spawnFlatRadius * 0.55, this.spawnFlatRadius * 1.75, distance);
    height *= 1 - flatten;

    // Raised boundary ridge closes the finite area and creates a horizon line.
    const rimStart = this.size * 0.34;
    const rim = smoothstep(rimStart, this.size * 0.5, distance);
    height += rim * rim * this.rimHeight;

    return height;
  }
}

/**
 * Pull two neighbouring samples toward each other when they exceed the slope
 * limit. Mutates `heights` in place and reports whether anything moved.
 */
function relaxPair(heights: Float32Array, a: number, b: number, maxDelta: number): boolean {
  const first = heights[a];
  const second = heights[b];
  if (first === undefined || second === undefined) {
    return false;
  }

  const difference = second - first;
  const magnitude = Math.abs(difference);
  if (magnitude <= maxDelta) {
    return false;
  }

  const excess = (magnitude - maxDelta) / 2;
  const direction = difference > 0 ? 1 : -1;
  heights[a] = first + excess * direction;
  heights[b] = second - excess * direction;
  return true;
}

function normalizeNormal(x: number, y: number, z: number): TerrainNormal {
  const length = Math.hypot(x, y, z);
  if (length === 0) {
    return { x: 0, y: 1, z: 0 };
  }
  return { x: x / length, y: y / length, z: z / length };
}
